def main():
    out = []
    out.append("/* Generated by android/tools/make_font.py - do not edit. */")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("/* Proportional 5x7 font with a 1 px descender, ASCII 32-126.")
    out.append(" * font5x7_width[c - 32] is the glyph width; font5x7_rows[c - 32][r] is row r")
    out.append(" * (0 = top, 6 = baseline, 7 = descender), bit 4 = leftmost pixel. */")
    widths = []
    rows_all = []
    for code in range(32, 127):
        ch = chr(code)
        if ch not in G:
            raise SystemExit("missing glyph %r" % ch)
        rows = G[ch]
        w = max(len(r) for r in rows)
        if code == 32:
            w = 2
        bits = []
        for r in rows:
            r = r.ljust(w, ".")
            v = 0
            for i, c in enumerate(r):
                if c == "#":
                    v |= 1 << (4 - i)
            bits.append(v)
        widths.append(w)
        rows_all.append(bits)
    out.append("static const uint8_t font5x7_width[95] = {%s};" % ", ".join(map(str, widths)))
    out.append("static const uint8_t font5x7_rows[95][8] = {")
    for code, bits in zip(range(32, 127), rows_all):
        name = chr(code)
        if name in "\\":
            name = "backslash"
        out.append("    {%s}, /* %s */" % (", ".join("0x%02X" % b for b in bits), name))
    out.append("};")
    print("\n".join(out))

if __name__ == "__main__":
    main()
